using Test, MPI, HDF5, LinearAlgebra, SHA, JSON3

"""Create an owned QE source with the same two-band spinor data used by the
existing full-operator recovery test. The raw EIG is generated by this source;
there is no external EIG or file-based NNKP provider in the solver config.
"""
function native_full_operator_owned_fixture(root)
    w = WannierNLQG.Wannierization
    r = WannierNLQG.Runtime
    directory = joinpath(root, "owned-full-posthoc")
    mkpath(directory)
    fixture = NativeReuseSupport.QEPAWMatrixElementsTestSupport.write_qe_paw_fixture(
        directory;
        spinor = true,
    )
    xml = joinpath(fixture.save_directory, "data-file-schema.xml")
    write(
        xml,
        replace(
            read(xml, String),
            "<nbnd>1</nbnd>" => "<nbnd>2</nbnd>",
            "<eigenvalues>-0.25</eigenvalues>" => "<eigenvalues>-0.25 -0.15</eigenvalues>",
        ),
    )
    g = hcat([Int[x, y, z] for x in -2:2 for y in -2:2 for z in -2:2]...)
    coefficients = exp.(-0.5 .* vec(sum(abs2, g; dims = 1)))
    coefficients ./= norm(coefficients)
    HDF5.h5open(joinpath(fixture.save_directory, "wfc1.hdf5"), "w") do h
        attrs = HDF5.attributes(h)
        attrs["igwx"] = length(coefficients)
        attrs["nbnd"] = 2
        attrs["npol"] = 2
        attrs["xk"] = [0.0, 0.0, 0.0]
        attrs["scale_factor"] = 1.0
        h["MillerIndices"] = g
        ma = HDF5.attributes(h["MillerIndices"])
        for i in 1:3
            ma["bg$i"] = Matrix{Float64}(I, 3, 3)[i, :]
        end
        spinors = zeros(ComplexF64, 2length(coefficients), 2)
        spinors[1:length(coefficients), 1] .= coefficients
        spinors[(length(coefficients) + 1):end, 2] .= coefficients
        isapprox(spinors' * spinors, Matrix{Float64}(I, 2, 2)) ||
            error("owned spinor fixture is not orthonormal")
        packed = zeros(4length(coefficients), 2)
        packed[1:2:end, :] .= real.(spinors)
        h["evc"] = packed
    end
    rm(fixture.nnkp_file)
    baseline_model = joinpath(directory, "baseline", "model.h5")
    baseline_checkpoint = joinpath(directory, "baseline", "state.wannierization.h5")
    mkpath(dirname(baseline_model))
    doc = Dict{String, Any}(
        "workflow" => "wannierization",
        "mode" => "ordinary",
        "source" => Dict(
            "kind" => "qe",
            "save_directory" => fixture.save_directory,
            "include_time_reversal" => false,
        ),
        "kmesh" => Dict("dimensions" => [1, 1, 1]),
        "basis" => Dict("projections" => ["X:s"], "spinor" => true),
        "solver" => Dict("initialization" => "amn", "dis_num_iter" => 0, "num_iter" => 0),
        "output" => Dict(
            "profile" => "hamiltonian_position",
            "model_file" => baseline_model,
            "checkpoint_hdf5" => baseline_checkpoint,
            "num_print_cycles" => 0,
            "num_dump_cycles" => 0,
        ),
    )
    config = r.resolve_workflow_input(doc; base_dir = directory).config
    w.uses_generated_native_eigenvalues(config.input) ||
        error("full-operator fixture must use owned topology and generated EIG")
    return (; directory, config, baseline_model, baseline_checkpoint)
end

function native_full_operator_posthoc_cases(root; parallel = :serial)
    w = WannierNLQG.Wannierization
    mpi_execution = parallel == :mpi
    rank = mpi_execution ? MPI.Comm_rank(MPI.COMM_WORLD) : 0
    prepared = if rank == 0
        try
            (; ok = true, value = native_full_operator_owned_fixture(root), error = "")
        catch exception
            (; ok = false, value = nothing, error = sprint(showerror, exception, catch_backtrace()))
        end
    else
        nothing
    end
    prepared = mpi_execution ? MPI.bcast(prepared, 0, MPI.COMM_WORLD) : prepared
    return @testset "Owned QE posthoc full operators from accepted H/r state" begin
        @test prepared.ok
        prepared.ok || error(prepared.error)
        f = prepared.value
        # Parallel mode is a numerical restart input. Construct the accepted H/r
        # state on the same actual rank topology as its full-profile continuation.
        baseline_config = w._replace_wannierization_config(f.config; solver = (; parallel))
        if mpi_execution
            @test_throws ArgumentError w.construct_wannier_functions(baseline_config)
        end
        # Only rank zero generates and captures the owned native matrices.
        # The existing shared-input entry then solves the genuine 12-rank H/r
        # baseline without concurrent writes to its accepted artifacts.
        captured = if rank == 0 && mpi_execution
            try
                extension = Base.get_extension(WannierNLQG, :WannierNLQGWannierizationExt)
                owner = extension.WorkflowOrchestration
                basis = owner._configured_projection_basis(baseline_config.input)
                config = owner._config_with_projection_basis(baseline_config, basis)
                matrices = owner._resolve_wannier_matrix_elements(config, basis)
                (; ok = true, reference = matrices.accepted_matrix_reference, error = "")
            catch exception
                (;
                    ok = false,
                    reference = nothing,
                    error = sprint(showerror, exception, catch_backtrace()),
                )
            end
        else
            nothing
        end
        captured = mpi_execution ? MPI.bcast(captured, 0, MPI.COMM_WORLD) : captured
        mpi_execution && !captured.ok && error(captured.error)
        baseline =
            mpi_execution ?
            w.construct_wannier_functions_with_native_inputs(baseline_config, captured.reference) :
            w.construct_wannier_functions(baseline_config)
        baseline.restart_state !== nothing ||
            error("owned H/r baseline has no accepted restart: $(baseline.diagnostics)")
        baseline.status in (w.COMPLETED, w.COMPLETED_WITH_WARNINGS, w.MAX_ITERATIONS) ||
            error("owned H/r baseline failed: $(baseline.diagnostics)")
        mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
        native_dir = baseline_config.input.matrix_elements.artifact_dir
        source_dir = baseline_config.input.source.save_directory
        before_native = NativeReuseSupport.inventory(native_dir)
        before_source = NativeReuseSupport.inventory(source_dir)
        before_checkpoint = bytes2hex(SHA.sha256(read(f.baseline_checkpoint)))
        before_model = bytes2hex(SHA.sha256(read(f.baseline_model)))
        output_dir = joinpath(f.directory, "fresh-full")
        model = joinpath(output_dir, "model.h5")
        checkpoint = joinpath(output_dir, "state.wannierization.h5")
        rank == 0 && mkpath(output_dir)
        mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
        expected = w.native_operator_artifact_paths(baseline_config.input, :full, ())
        @test w.uses_generated_native_eigenvalues(baseline_config.input)
        @test length(expected) == 10
        @test all(!ispath(path) for path in values(expected))
        fresh_dir = joinpath(output_dir, "native-operators")
        fresh_paths =
            (; (field => joinpath(fresh_dir, basename(path)) for (field, path) in expected)...)
        cfg = w._replace_wannierization_config(
            baseline_config;
            solver = (; initialization = :restart, parallel),
            checkpoint = (; restart_hdf5 = f.baseline_checkpoint, checkpoint_hdf5 = checkpoint),
            output = merge((; model_file = model, profile = :full), fresh_paths),
        )
        @test w.validate_native_operator_artifact_paths(cfg) ==
              Dict(field => getfield(fresh_paths, field) for field in keys(expected))
        bad = w._replace_wannierization_config(cfg; output = (; spn_file = expected[:spn_file]))
        @test_throws ArgumentError w.validate_native_operator_artifact_paths(bad)
        result =
            mpi_execution ?
            w.construct_wannier_functions_with_native_inputs(cfg, captured.reference) :
            w.construct_wannier_functions(cfg)
        mpi_execution && @test result.input_summary["native_matrix_input_origin"] ==
              "VALIDATED_ACCEPTED_INPUT_REUSE_TERMINAL_OPERATOR_POSTHOC"
        @test result.status ∉ (w.INVALID_INPUT, w.IO_FAILURE, w.LOCALIZATION_FAILED)
        @test result.status == baseline.status
        @test isequal(result.v_matrix, baseline.v_matrix)
        @test isequal(result.spreads_angstrom2, baseline.spreads_angstrom2)
        @test !any(d -> d.code == :TB_EXPORT_FAILED, result.diagnostics)
        @test all(isfile, values(w.validate_native_operator_artifact_paths(cfg)))
        @test isfile(model)
        @test isfile(checkpoint)
        @test result.restart_state !== nothing
        if result.restart_state !== nothing
            @test haskey(
                result.restart_state.input_definition.auxiliary_sources,
                "operator_profile_sources",
            )
        end
        @test NativeReuseSupport.inventory(native_dir) == before_native
        @test NativeReuseSupport.inventory(source_dir) == before_source
        @test bytes2hex(SHA.sha256(read(f.baseline_checkpoint))) == before_checkpoint
        @test bytes2hex(SHA.sha256(read(f.baseline_model))) == before_model
        if !mpi_execution && all(isfile, values(w.validate_native_operator_artifact_paths(cfg)))
            # Reuse the complete pair from the just-finished full publication;
            # SPN and spin-neighbor operators are independently regenerated.
            reuse_output = joinpath(f.directory, "reuse-complete-pair")
            reuse_native = joinpath(reuse_output, "native-operators")
            mkpath(reuse_native)
            for name in (
                "native.uIu",
                "native.uIu.provenance.json",
                "native.uIu.provenance.json.references.h5",
                "native.uHu",
                "native.uHu.provenance.json",
                "native.uHu.provenance.json.references.h5",
            )
                cp(joinpath(fresh_dir, name), joinpath(reuse_native, name))
            end
            reused_paths = (;
                (field => joinpath(reuse_native, basename(path)) for (field, path) in expected)...
            )
            execution =
                w._replace_wannierization_group(cfg.input.preparation_execution, (; resume = true))
            reuse_cfg = w._replace_wannierization_config(
                cfg;
                input = (; preparation_execution = execution),
                output = merge((; model_file = joinpath(reuse_output, "model.h5")), reused_paths),
                checkpoint = (; checkpoint_hdf5 = joinpath(reuse_output, "state.h5")),
            )
            before_pair = Dict(
                name => bytes2hex(SHA.sha256(read(joinpath(reuse_native, name)))) for
                name in ("native.uIu", "native.uHu")
            )
            reused = w.construct_wannier_functions(reuse_cfg)
            @test reused.status == baseline.status
            @test isequal(reused.v_matrix, baseline.v_matrix)
            @test !any(d -> d.code == :TB_EXPORT_FAILED, reused.diagnostics)
            @test isfile(joinpath(reuse_output, "model.h5"))
            @test all(
                name ->
                    bytes2hex(SHA.sha256(read(joinpath(reuse_native, name)))) == before_pair[name],
                keys(before_pair),
            )
        end
        # Reuse uIu/uHu plus SPN, then generate only the missing spin links.
        # Deliberately mutate a separate SPN copy to test byte-level rejection.
        if !mpi_execution && all(isfile, values(w.validate_native_operator_artifact_paths(cfg)))
            pair_spn_output = joinpath(f.directory, "reuse-pair-and-spn")
            pair_spn_native = joinpath(pair_spn_output, "native-operators")
            mkpath(pair_spn_native)
            reuse_names = (
                "native.uIu",
                "native.uIu.provenance.json",
                "native.uIu.provenance.json.references.h5",
                "native.uHu",
                "native.uHu.provenance.json",
                "native.uHu.provenance.json.references.h5",
                "native.spn",
                "native.spn.json",
            )
            for name in reuse_names
                ;
                cp(joinpath(fresh_dir, name), joinpath(pair_spn_native, name));
            end
            spin_paths = (;
                (
                    field => joinpath(pair_spn_native, basename(path)) for
                    (field, path) in expected
                )...
            )
            spin_exec =
                w._replace_wannierization_group(cfg.input.preparation_execution, (; resume = true))
            spin_cfg = w._replace_wannierization_config(
                cfg;
                input = (; preparation_execution = spin_exec),
                output = merge((; model_file = joinpath(pair_spn_output, "model.h5")), spin_paths),
                checkpoint = (; checkpoint_hdf5 = joinpath(pair_spn_output, "state.h5")),
            )
            before_spin = Dict(
                name=>bytes2hex(SHA.sha256(read(joinpath(pair_spn_native, name)))) for
                name in reuse_names
            )
            spin_result = w.construct_wannier_functions(spin_cfg)
            if spin_result.status in (w.INVALID_INPUT, w.IO_FAILURE, w.LOCALIZATION_FAILED)
                println(
                    stderr,
                    "PAIR_SPN_DIAGNOSTICS=",
                    [(d.code, d.message) for d in spin_result.diagnostics],
                )
            end
            @test spin_result.status == baseline.status
            @test isequal(spin_result.v_matrix, baseline.v_matrix)
            @test isfile(joinpath(pair_spn_output, "model.h5"))
            @test all(
                name->bytes2hex(SHA.sha256(read(joinpath(pair_spn_native, name)))) ==
                      before_spin[name],
                reuse_names,
            )
            bad_output=joinpath(f.directory, "reuse-pair-spn-tampered")
            bad_native=joinpath(bad_output, "native-operators");
            mkpath(bad_native)
            for name in reuse_names
                ;
                cp(joinpath(fresh_dir, name), joinpath(bad_native, name));
            end
            open(joinpath(bad_native, "native.spn"), "r+") do io
                seekend(io);
                seek(io, position(io)-1);
                b=read(io, UInt8);
                seek(io, position(io)-1);
                write(io, b ⊻ 0x01)
            end
            bad_paths=(;
                (field=>joinpath(bad_native, basename(path)) for (field, path) in expected)...
            )
            bad_cfg=w._replace_wannierization_config(
                spin_cfg;
                output = merge((; model_file = joinpath(bad_output, "model.h5")), bad_paths),
                checkpoint = (; checkpoint_hdf5 = joinpath(bad_output, "state.h5")),
            )
            bad_result=w.construct_wannier_functions(bad_cfg)
            @test bad_result.status in (w.INVALID_INPUT, w.IO_FAILURE, w.LOCALIZATION_FAILED)
            @test !isfile(joinpath(bad_output, "model.h5"))
        end
        # Exercise a complete published set after an interrupted final assembly.
        # Each rank retains the same accepted gauge; only rank 0 owns durable metadata.
        if all(isfile, values(w.validate_native_operator_artifact_paths(cfg)))
            all_output = joinpath(f.directory, "reuse-complete-set")
            all_native = joinpath(all_output, "native-operators")
            all_names = (
                "native.spn",
                "native.spn.json",
                "native.uIu",
                "native.uIu.provenance.json",
                "native.uIu.provenance.json.references.h5",
                "native.uHu",
                "native.uHu.provenance.json",
                "native.uHu.provenance.json.references.h5",
                "native.sIu",
                "native.sIu.provenance.json",
                "native.sIu.provenance.json.references.h5",
                "native.sHu",
                "native.sHu.provenance.json",
                "native.sHu.provenance.json.references.h5",
            )
            if rank == 0
                mkpath(all_native)
                for name in all_names
                    ;
                    cp(joinpath(fresh_dir, name), joinpath(all_native, name));
                end
            end
            mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
            all_paths =
                (; (field => joinpath(all_native, basename(path)) for (field, path) in expected)...)
            execution =
                w._replace_wannierization_group(cfg.input.preparation_execution, (; resume = true))
            all_cfg = w._replace_wannierization_config(
                cfg;
                input = (; preparation_execution = execution),
                output = merge((; model_file = joinpath(all_output, "model.h5")), all_paths),
                checkpoint = (; checkpoint_hdf5 = joinpath(all_output, "state.h5")),
            )
            before_all =
                rank == 0 ?
                Dict(
                    name => bytes2hex(SHA.sha256(read(joinpath(all_native, name)))) for
                    name in all_names
                ) : nothing
            all_result =
                mpi_execution ?
                w.construct_wannier_functions_with_native_inputs(all_cfg, captured.reference) :
                w.construct_wannier_functions(all_cfg)
            @test all_result.status == baseline.status
            @test isequal(all_result.v_matrix, baseline.v_matrix)
            if rank == 0
                @test haskey(
                    all_result.input_summary,
                    "operator_profile_preflight_operator_target_contract_definition",
                )
                @test isfile(joinpath(all_output, "model.h5"))
                @test all(
                    name ->
                        bytes2hex(SHA.sha256(read(joinpath(all_native, name)))) == before_all[name],
                    all_names,
                )
            elseif mpi_execution
                @test all_result.input_summary["operator_profile_preflight_nonroot_metadata_scope"] ==
                      "COMPLETE_DEFINITIONS_ON_PUBLISHING_RANK"
            end
            # A subsequent terminal checkpoint may consume that exact existing
            # publication in place, while writing its new result elsewhere.
            second_output = joinpath(f.directory, "resume-existing-operators")
            if rank == 0
                ;
                mkpath(second_output);
            end
            mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
            second_cfg = w._replace_wannierization_config(
                all_cfg;
                output = (; model_file = joinpath(second_output, "model.h5")),
                checkpoint = (;
                    restart_hdf5 = joinpath(all_output, "state.h5"),
                    checkpoint_hdf5 = joinpath(second_output, "state.h5"),
                ),
            )
            @test w.validate_native_operator_artifact_paths(second_cfg) ==
                  Dict(field => getfield(all_paths, field) for field in keys(expected))
            second =
                mpi_execution ?
                w.construct_wannier_functions_with_native_inputs(second_cfg, captured.reference) :
                w.construct_wannier_functions(second_cfg)
            @test second.status == baseline.status
            @test isequal(second.v_matrix, baseline.v_matrix)
            if rank == 0
                @test isfile(joinpath(second_output, "model.h5"))
                @test all(
                    name ->
                        bytes2hex(SHA.sha256(read(joinpath(all_native, name)))) == before_all[name],
                    all_names,
                )
            end
            # The same complete set is also usable from the original H/r
            # checkpoint, avoiding large per-rank full-checkpoint metadata.
            hr_output = joinpath(f.directory, "resume-hr-existing-operators")
            rank == 0 && mkpath(hr_output)
            mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
            hr_cfg = w._replace_wannierization_config(
                second_cfg;
                output = (; model_file = joinpath(hr_output, "model.h5")),
                checkpoint = (;
                    restart_hdf5 = f.baseline_checkpoint,
                    checkpoint_hdf5 = joinpath(hr_output, "state.h5"),
                ),
            )
            # An incomplete external set must never invoke a generator in the
            # old directory. Missing paths are rejected at the planning boundary.
            partial_dir = joinpath(f.directory, "partial-external-operators")
            if rank == 0
                mkpath(partial_dir)
                cp(joinpath(all_native, "native.uIu"), joinpath(partial_dir, "native.uIu"))
            end
            mpi_execution && MPI.Barrier(MPI.COMM_WORLD)
            partial_paths = (;
                (field => joinpath(partial_dir, basename(path)) for (field, path) in expected)...
            )
            partial_cfg = w._replace_wannierization_config(hr_cfg; output = partial_paths)
            @test_throws ArgumentError w.validate_native_operator_artifact_paths(partial_cfg)
            hr_result =
                mpi_execution ?
                w.construct_wannier_functions_with_native_inputs(hr_cfg, captured.reference) :
                w.construct_wannier_functions(hr_cfg)
            @test hr_result.status == baseline.status
            @test isequal(hr_result.v_matrix, baseline.v_matrix)
            if rank == 0
                @test isfile(joinpath(hr_output, "model.h5"))
                @test all(
                    name ->
                        bytes2hex(SHA.sha256(read(joinpath(all_native, name)))) == before_all[name],
                    all_names,
                )
            end
        end
    end
end
