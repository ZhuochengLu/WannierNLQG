# Bounded, synchronous fan-out of the exact serialized bytes. The sink must consume
# each borrowed buffer before returning; it cannot retain or mutate that buffer.
mutable struct WannierTBWriteStream{T <: Base.IO, F} <: Base.IO
    stream::T
    sink::F
    buffer::Vector{UInt8}
    used::Int
    byte_count::Int
end
# Wrap the output stream and optional byte sink with an initially empty 64 KiB buffer.
WannierTBWriteStream(stream::Base.IO, sink) =
    WannierTBWriteStream(stream, sink, Vector{UInt8}(undef, 65536), 0, 0)
# Expose the underlying stream open state without changing buffered byte ownership.
Base.isopen(io::WannierTBWriteStream) = isopen(io.stream)
# Expose the underlying stream writability for the buffered Wannier text writer.
Base.iswritable(io::WannierTBWriteStream) = iswritable(io.stream)
# Report the logical byte position including bytes not yet flushed to the underlying stream.
Base.position(io::WannierTBWriteStream) = io.byte_count + io.used
# Flush exactly the used bytes, verify the write count and pass those same bytes to the optional sink.
function _flush_wannier_tb_bytes!(io::WannierTBWriteStream)
    io.used == 0 && return nothing
    bytes = @view io.buffer[1:io.used]
    written = write(io.stream, bytes)
    written == io.used || error("IncompleteWannierTBWrite")
    io.sink === nothing || io.sink(bytes)
    io.byte_count += io.used
    io.used = 0
    return nothing
end
# Append one byte to the owned buffer, flushing first only when the buffer is full.
function Base.write(io::WannierTBWriteStream, byte::UInt8)
    io.used == length(io.buffer) && _flush_wannier_tb_bytes!(io)
    io.used += 1
    io.buffer[io.used] = byte
    return 1
end
# Copy the requested pointer bytes into the owned buffer in bounded chunks while preserving its storage.
function Base.unsafe_write(io::WannierTBWriteStream, pointer::Ptr{UInt8}, count::UInt)
    remaining = Int(count)
    offset = 0
    while remaining > 0
        io.used == length(io.buffer) && _flush_wannier_tb_bytes!(io)
        amount = min(remaining, length(io.buffer) - io.used)
        GC.@preserve io unsafe_copyto!(
            Base.pointer(io.buffer, io.used + 1),
            pointer + offset,
            amount,
        )
        io.used += amount
        offset += amount
        remaining -= amount
    end
    return Int(count)
end
# Drain the owned buffer before flushing the underlying output stream.
Base.flush(io::WannierTBWriteStream) = (_flush_wannier_tb_bytes!(io); flush(io.stream))

# Write Wannier degeneracies in rows of at most fifteen integers.
function _write_wannier_degeneracies(io::Base.IO, degeneracies::Vector{Int})
    for start in 1:15:length(degeneracies)
        stop = min(start + 14, length(degeneracies))
        for value in @view degeneracies[start:stop]
            @printf(io, "%5d", value)
        end
        println(io)
    end
    return nothing
end

"""
Write a complete Wannier-compatible `_tb.dat` model.

The writer preserves the model's row-lattice and real-space-last Julia layout.
Hamiltonian/position values are written in the existing model's serialized
convention; degeneracy division remains owned by Fourier interpolation. The
destination is never overwritten unless requested.
"""
function write_wannier_tb(
    filename::AbstractString,
    model::TightBindingModel;
    comment::AbstractString = "Generated by WannierNLQG",
    overwrite::Bool = false,
    byte_sink = nothing,
    return_receipt::Bool = false,
)
    ispath(filename) &&
        !overwrite &&
        throw(ArgumentError("refusing to overwrite existing TB file: $(filename)"))
    parent = dirname(abspath(filename))
    mkpath(parent)
    receipt = open(filename, "w") do stream
        io = WannierTBWriteStream(stream, byte_sink)
        println(io, join(split(String(comment)), ' '))
        for row in 1:3
            @printf(io, "%22.14e%22.14e%22.14e\n", model.lattice[row, :]...)
        end
        println(io, model.num_orbitals)
        println(io, model.num_r_vectors)
        _write_wannier_degeneracies(io, model.r_degeneracies)
        for r_index in 1:model.num_r_vectors
            println(io)
            @printf(io, "%5d%5d%5d\n", model.r_vectors[:, r_index]...)
            for column in 1:model.num_orbitals, row in 1:model.num_orbitals
                value = model.hamiltonian_r[row, column, r_index]
                @printf(io, "%5d%5d%22.14e%22.14e\n", row, column, real(value), imag(value))
            end
        end
        for r_index in 1:model.num_r_vectors
            println(io)
            @printf(io, "%5d%5d%5d\n", model.r_vectors[:, r_index]...)
            for column in 1:model.num_orbitals, row in 1:model.num_orbitals
                @printf(io, "%5d%5d", row, column)
                for cartesian in 1:3
                    value = model.position_r[row, column, cartesian, r_index]
                    @printf(io, "%22.14e%22.14e", real(value), imag(value))
                end
                println(io)
            end
        end
        flush(io)
        (; path = String(filename), bytes = io.byte_count)
    end
    return return_receipt ? receipt : String(filename)
end
